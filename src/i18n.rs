//! Minimal i18n: English strings are the keys, Chinese is looked up when enabled.
//! The Linux VT (TERM=linux) cannot render CJK glyphs, so Chinese is never used there.

use std::collections::HashMap;
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::OnceLock;

static ZH: AtomicBool = AtomicBool::new(false);

pub fn cjk_capable() -> bool {
    std::env::var("TERM").map(|t| t != "linux").unwrap_or(false)
}

/// `lang`: "en", "zh" or "auto" (zh when LANG starts with zh and the terminal can show it).
pub fn init(lang: &str) {
    let zh = match lang {
        "zh" => cjk_capable(),
        "en" => false,
        _ => {
            cjk_capable()
                && std::env::var("LANG")
                    .or_else(|_| std::env::var("LC_ALL"))
                    .map(|l| l.starts_with("zh"))
                    .unwrap_or(false)
        }
    };
    ZH.store(zh, Ordering::Relaxed);
}

pub fn is_zh() -> bool {
    ZH.load(Ordering::Relaxed)
}

/// Toggle language; returns false if the terminal cannot show Chinese.
pub fn toggle() -> bool {
    if !is_zh() && !cjk_capable() {
        return false;
    }
    ZH.store(!is_zh(), Ordering::Relaxed);
    true
}

pub fn tr(s: &str) -> &str {
    if !is_zh() {
        return s;
    }
    dict().get(s).copied().unwrap_or(s)
}

